# Function to calculate scores for each combination
def calculate_scores_for_point(cost_weight, acne_weight):
    # Modify weights based on the current point
    weights_dict = {
        'arm_implant': copy.deepcopy(original_weight_arm_implant),
        'patch': copy.deepcopy(original_weight_patch),
        'combo_pill': copy.deepcopy(original_weight_combo_pill),
        'mini_pill': copy.deepcopy(original_weight_mini_pill),
        'ring': copy.deepcopy(original_weight_ring),
        'shot': copy.deepcopy(original_weight_shot)
    }
    
    # Update cost effectiveness weights
    cost_weights = [-3 * (cost_weight/20), -2 * (cost_weight/20), -1 * (cost_weight/20),
                    1 * (cost_weight/20), 2 * (cost_weight/20), 3 * (cost_weight/20)]
    
    for method in weights_dict:
        if method in ['patch', 'combo_pill', 'mini_pill', 'ring']:
            weights_dict[method][0] = cost_weights
    
    # Update acne weights
    for method in weights_dict:
        if method in ['arm_implant', 'patch', 'combo_pill', 'mini_pill', 'ring', 'shot']:
            if acne_weight == 0:
                weights_dict[method][8] = 3  # no acne
            else:
                weights_dict[method][8] = acne_weight  # mild, moderate, or severe
    
    # Calculate scores
    scores = {}
    input_arr = base_input.copy()
    
    # Set acne value in input array
    if acne_weight == 0:
        input_arr[11] = 'no'
    elif acne_weight == -15:
        input_arr[11] = 'mild'
    elif acne_weight == -25:
        input_arr[11] = 'moderate'
    else:
        input_arr[11] = 'severe'
    
    # Calculate scores for each method
    patch_arr = ["patch"] + input_arr
    combo_pill_arr = ["combo_pill"] + input_arr
    mini_pill_arr = ["mini_pill"] + input_arr
    ring_arr = ["ring"] + input_arr
    
    scores['Patch'] = change_score_patch(patch_arr, weights_dict['patch'])
    scores['Combination Pill'] = change_score_combo_pill(combo_pill_arr, weights_dict['combo_pill'])
    scores['Mini Pill'] = change_scoring_mini_pill(mini_pill_arr, weights_dict['mini_pill'])
    scores['Ring'] = score_ring(ring_arr, weights_dict['ring'])
    
    return scores

